USE mahn_db;

-- =============================================================================
-- 1. TABLAS
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Catálogo de tipos de museo
-- -----------------------------------------------------------------------------
CREATE TABLE tipos_museo (
    id_tipo_museo TINYINT UNSIGNED NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador del tipo de museo',
    nombre        VARCHAR(30)      NOT NULL
        COMMENT 'Nombre del tipo de museo: Arte, Historia, Musical o Militar',
    CONSTRAINT pk_tipos_museo PRIMARY KEY (id_tipo_museo),
    CONSTRAINT uq_tipos_museo_nombre UNIQUE (nombre)
) ENGINE = InnoDB
  COMMENT = 'Catálogo de los tipos de museo';

-- -----------------------------------------------------------------------------
-- Catálogo de áreas de investigación / temáticas de las salas
-- -----------------------------------------------------------------------------
CREATE TABLE areas (
    id_area     TINYINT UNSIGNED NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador del área',
    nombre      VARCHAR(60)      NOT NULL
        COMMENT 'Nombre del área (Antropología, Paleontología, Genoma, etc.)',
    descripcion VARCHAR(255)     NOT NULL
        COMMENT 'Descripción breve del área',
    CONSTRAINT pk_areas PRIMARY KEY (id_area),
    CONSTRAINT uq_areas_nombre UNIQUE (nombre)
) ENGINE = InnoDB
  COMMENT = 'Catálogo de áreas de investigación y temáticas a las que pertenece cada sala';

-- -----------------------------------------------------------------------------
-- Museos
-- -----------------------------------------------------------------------------
CREATE TABLE museos (
    id_museo        INT UNSIGNED     NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador del museo',
    id_tipo_museo   TINYINT UNSIGNED NOT NULL
        COMMENT 'Tipo de museo (FK a tipos_museo)',
    nombre          VARCHAR(120)     NOT NULL
        COMMENT 'Nombre del museo',
    ubicacion       VARCHAR(200)     NOT NULL
        COMMENT 'Dirección o ubicación del museo',
    fecha_fundacion DATE             NOT NULL
        COMMENT 'Fecha de fundación del museo',
    director        VARCHAR(100)     NOT NULL
        COMMENT 'Nombre de la persona que dirige el museo',
    sitio_web       VARCHAR(200)     NULL
        COMMENT 'Sitio web oficial (debe iniciar con http:// o https://)',
    CONSTRAINT pk_museos PRIMARY KEY (id_museo),
    CONSTRAINT uq_museos_nombre UNIQUE (nombre),
    INDEX ix_museos_id_tipo_museo (id_tipo_museo),
    CONSTRAINT fk_museos_tipos_museo FOREIGN KEY (id_tipo_museo)
        REFERENCES tipos_museo (id_tipo_museo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_museos_sitio_web CHECK (sitio_web IS NULL OR sitio_web LIKE 'http://%' OR sitio_web LIKE 'https://%')
) ENGINE = InnoDB
  COMMENT = 'Museos cuyas salas se administran y venden en la aplicación';

-- -----------------------------------------------------------------------------
-- Salas
-- -----------------------------------------------------------------------------
CREATE TABLE salas (
    id_sala     INT UNSIGNED     NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador de la sala (se codifica en el QR de la sala)',
    id_museo    INT UNSIGNED     NOT NULL
        COMMENT 'Museo al que pertenece la sala (FK a museos)',
    id_area     TINYINT UNSIGNED NOT NULL
        COMMENT 'Área de investigación o temática de la sala (FK a areas)',
    nombre      VARCHAR(120)     NOT NULL
        COMMENT 'Nombre de la sala',
    descripcion VARCHAR(600)     NOT NULL
        COMMENT 'Descripción de la sala',
    CONSTRAINT pk_salas PRIMARY KEY (id_sala),
    CONSTRAINT uq_salas_museo_nombre UNIQUE (id_museo, nombre),
    INDEX ix_salas_id_area (id_area),
    CONSTRAINT fk_salas_museos FOREIGN KEY (id_museo)
        REFERENCES museos (id_museo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_salas_areas FOREIGN KEY (id_area)
        REFERENCES areas (id_area)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE = InnoDB
  COMMENT = 'Salas de exhibición de cada museo';

-- -----------------------------------------------------------------------------
-- Colecciones que se muestran en las salas
-- -----------------------------------------------------------------------------
CREATE TABLE colecciones (
    id_coleccion INT UNSIGNED  NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador de la colección',
    id_sala      INT UNSIGNED  NOT NULL
        COMMENT 'Sala donde se exhibe la colección (FK a salas)',
    nombre       VARCHAR(120)  NOT NULL
        COMMENT 'Nombre de la colección',
    siglo        SMALLINT      NOT NULL
        COMMENT 'Siglo al que pertenece la colección: positivo = d. C., negativo = a. C. (ej. 20 = siglo XX, -1 = siglo I a. C.)',
    descripcion  VARCHAR(1000) NOT NULL
        COMMENT 'Observación o descripción detallada de lo que representa la colección',
    CONSTRAINT pk_colecciones PRIMARY KEY (id_coleccion),
    CONSTRAINT uq_colecciones_sala_nombre UNIQUE (id_sala, nombre),
    CONSTRAINT fk_colecciones_salas FOREIGN KEY (id_sala)
        REFERENCES salas (id_sala)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_colecciones_siglo CHECK (siglo <> 0 AND siglo BETWEEN -100 AND 22)
) ENGINE = InnoDB
  COMMENT = 'Colecciones que se exhiben en las salas';

-- -----------------------------------------------------------------------------
-- Especies en exhibición dentro de las colecciones
-- -----------------------------------------------------------------------------
CREATE TABLE especies (
    id_especie        INT UNSIGNED   NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador de la especie en exhibición',
    id_coleccion      INT UNSIGNED   NOT NULL
        COMMENT 'Colección a la que pertenece el ejemplar (FK a colecciones)',
    nombre_cientifico VARCHAR(120)   NOT NULL
        COMMENT 'Nombre científico (binomial) de la especie',
    nombre_comun      VARCHAR(120)   NOT NULL
        COMMENT 'Nombre común de la especie',
    fecha_extincion   VARCHAR(80)    NULL
        COMMENT 'Fecha o periodo aproximado de extinción; NULL si la especie no está extinta',
    epoca             VARCHAR(100)   NOT NULL
        COMMENT 'Época geológica o histórica en la que vivió en la Tierra',
    peso_kg           DECIMAL(16, 6) NOT NULL
        COMMENT 'Peso promedio de un adulto en kilogramos',
    tamano_m          DECIMAL(10, 4) NOT NULL
        COMMENT 'Tamaño representativo (largo, altura o envergadura) en metros',
    caracteristicas   VARCHAR(1000)  NOT NULL
        COMMENT 'Características principales de la especie',
    ruta_imagen       VARCHAR(255)   NULL
        COMMENT 'Ruta relativa de la imagen (carpeta imagenes/ o recursos de la aplicación)',
    CONSTRAINT pk_especies PRIMARY KEY (id_especie),
    CONSTRAINT uq_especies_coleccion_nombre UNIQUE (id_coleccion, nombre_cientifico),
    CONSTRAINT fk_especies_colecciones FOREIGN KEY (id_coleccion)
        REFERENCES colecciones (id_coleccion)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_especies_peso CHECK (peso_kg > 0),
    CONSTRAINT ck_especies_tamano CHECK (tamano_m > 0)
) ENGINE = InnoDB
  COMMENT = 'Especies que se exhiben en cada colección';

-- -----------------------------------------------------------------------------
-- Temáticas (salas que no exhiben especies)
-- -----------------------------------------------------------------------------
CREATE TABLE tematicas (
    id_tematica     INT UNSIGNED  NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador de la temática',
    id_sala         INT UNSIGNED  NOT NULL
        COMMENT 'Sala que presenta la temática (FK a salas)',
    nombre          VARCHAR(120)  NOT NULL
        COMMENT 'Nombre de la temática',
    caracteristicas VARCHAR(1000) NOT NULL
        COMMENT 'Características de la temática',
    epoca           VARCHAR(100)  NOT NULL
        COMMENT 'Época a la que corresponde la temática',
    ruta_imagen     VARCHAR(255)  NULL
        COMMENT 'Ruta relativa de la imagen de la temática',
    CONSTRAINT pk_tematicas PRIMARY KEY (id_tematica),
    CONSTRAINT uq_tematicas_sala_nombre UNIQUE (id_sala, nombre),
    CONSTRAINT fk_tematicas_salas FOREIGN KEY (id_sala)
        REFERENCES salas (id_sala)
        ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE = InnoDB
  COMMENT = 'Temáticas de las salas que no son de exhibición de especies';

-- -----------------------------------------------------------------------------
-- Precios por sala (lunes a sábado y domingo)
-- -----------------------------------------------------------------------------
CREATE TABLE precios (
    id_precio      INT UNSIGNED   NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador del precio',
    id_sala        INT UNSIGNED   NOT NULL
        COMMENT 'Sala a la que corresponde el precio (FK a salas, uno por sala)',
    precio_semana  DECIMAL(10, 2) NOT NULL
        COMMENT 'Precio de la entrada de lunes a sábado en dólares (USD)',
    precio_domingo DECIMAL(10, 2) NOT NULL
        COMMENT 'Precio diferido de la entrada los domingos en dólares (USD)',
    CONSTRAINT pk_precios PRIMARY KEY (id_precio),
    CONSTRAINT uq_precios_sala UNIQUE (id_sala),
    CONSTRAINT fk_precios_salas FOREIGN KEY (id_sala)
        REFERENCES salas (id_sala)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_precios_semana CHECK (precio_semana >= 0),
    CONSTRAINT ck_precios_domingo CHECK (precio_domingo >= 0)
) ENGINE = InnoDB
  COMMENT = 'Precio de entrada de cada sala según el día de la semana';

-- -----------------------------------------------------------------------------
-- Tarjetas aceptadas y su comisión
-- -----------------------------------------------------------------------------
CREATE TABLE tarjetas (
    id_tarjeta          TINYINT UNSIGNED NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador de la tarjeta',
    nombre              VARCHAR(40)      NOT NULL
        COMMENT 'Marca de la tarjeta: VISA, Mastercard, American Express, Diners Club, Union Pay',
    porcentaje_comision DECIMAL(5, 2)    NOT NULL
        COMMENT 'Porcentaje de comisión que cobra la marca por transacción',
    activa              BOOLEAN          NOT NULL DEFAULT TRUE
        COMMENT 'Indica si la tarjeta se acepta actualmente en las cajas',
    CONSTRAINT pk_tarjetas PRIMARY KEY (id_tarjeta),
    CONSTRAINT uq_tarjetas_nombre UNIQUE (nombre),
    CONSTRAINT ck_tarjetas_porcentaje CHECK (porcentaje_comision BETWEEN 0 AND 100)
) ENGINE = InnoDB
  COMMENT = 'Tipos de tarjeta aceptados y la comisión que cobra cada marca';

-- -----------------------------------------------------------------------------
-- Entradas vendidas (encabezado)
-- -----------------------------------------------------------------------------
CREATE TABLE entradas (
    id_entrada       INT UNSIGNED     NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador de la entrada',
    codigo           CHAR(12)         NOT NULL
        COMMENT 'Código único de la entrada que se codifica en el QR',
    nombre_visitante VARCHAR(100)     NOT NULL
        COMMENT 'Nombre de la persona visitante',
    id_tarjeta       TINYINT UNSIGNED NOT NULL
        COMMENT 'Tarjeta con la que se pagó (FK a tarjetas)',
    fecha_compra     DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP
        COMMENT 'Fecha y hora de la venta',
    subtotal         DECIMAL(10, 2)   NOT NULL
        COMMENT 'Suma de los precios de las salas (USD)',
    iva              DECIMAL(10, 2)   NOT NULL
        COMMENT 'Impuesto al valor agregado del 13 % sobre el subtotal (USD)',
    total            DECIMAL(10, 2)   NOT NULL
        COMMENT 'Total pagado = subtotal + IVA (USD)',
    CONSTRAINT pk_entradas PRIMARY KEY (id_entrada),
    CONSTRAINT uq_entradas_codigo UNIQUE (codigo),
    INDEX ix_entradas_id_tarjeta (id_tarjeta),
    INDEX ix_entradas_fecha_compra (fecha_compra),
    CONSTRAINT fk_entradas_tarjetas FOREIGN KEY (id_tarjeta)
        REFERENCES tarjetas (id_tarjeta)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_entradas_montos CHECK (subtotal >= 0 AND iva >= 0 AND total = subtotal + iva)
) ENGINE = InnoDB
  COMMENT = 'Entradas vendidas en las cajas del museo';

-- -----------------------------------------------------------------------------
-- Detalle de cada entrada: sala y día de visita
-- -----------------------------------------------------------------------------
CREATE TABLE detalles_entrada (
    id_detalle   INT UNSIGNED   NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador del detalle',
    id_entrada   INT UNSIGNED   NOT NULL
        COMMENT 'Entrada a la que pertenece el detalle (FK a entradas)',
    id_sala      INT UNSIGNED   NOT NULL
        COMMENT 'Sala que se visitará (FK a salas)',
    fecha_visita DATE           NOT NULL
        COMMENT 'Día en que la entrada autoriza el ingreso a la sala',
    precio       DECIMAL(10, 2) NOT NULL
        COMMENT 'Precio cobrado según el día de la semana (USD)',
    CONSTRAINT pk_detalles_entrada PRIMARY KEY (id_detalle),
    CONSTRAINT uq_detalles_entrada_sala_fecha UNIQUE (id_entrada, id_sala, fecha_visita),
    INDEX ix_detalles_entrada_id_sala (id_sala),
    INDEX ix_detalles_entrada_fecha_visita (fecha_visita),
    CONSTRAINT fk_detalles_entrada_entradas FOREIGN KEY (id_entrada)
        REFERENCES entradas (id_entrada)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_detalles_entrada_salas FOREIGN KEY (id_sala)
        REFERENCES salas (id_sala)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_detalles_entrada_precio CHECK (precio >= 0)
) ENGINE = InnoDB
  COMMENT = 'Salas y días de visita incluidos en cada entrada';

-- -----------------------------------------------------------------------------
-- Comisiones cobradas (se llena automáticamente con el disparador tg_entradas_ai)
-- -----------------------------------------------------------------------------
CREATE TABLE comisiones_cobradas (
    id_comision         INT UNSIGNED     NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador del registro de comisión',
    id_entrada          INT UNSIGNED     NOT NULL
        COMMENT 'Entrada que originó la comisión (FK a entradas, una por entrada)',
    id_tarjeta          TINYINT UNSIGNED NOT NULL
        COMMENT 'Marca de tarjeta a la que se debe pagar la comisión (FK a tarjetas)',
    porcentaje_aplicado DECIMAL(5, 2)    NOT NULL
        COMMENT 'Porcentaje de comisión vigente al momento de la venta',
    monto_transaccion   DECIMAL(10, 2)   NOT NULL
        COMMENT 'Monto total cobrado a la tarjeta (USD)',
    monto_comision      DECIMAL(10, 2)   NOT NULL
        COMMENT 'Valor de la comisión = monto_transaccion * porcentaje_aplicado / 100 (USD)',
    fecha_registro      DATETIME         NOT NULL
        COMMENT 'Fecha y hora de la venta que generó la comisión',
    CONSTRAINT pk_comisiones_cobradas PRIMARY KEY (id_comision),
    CONSTRAINT uq_comisiones_cobradas_entrada UNIQUE (id_entrada),
    INDEX ix_comisiones_cobradas_id_tarjeta (id_tarjeta),
    INDEX ix_comisiones_cobradas_fecha_registro (fecha_registro),
    CONSTRAINT fk_comisiones_cobradas_entradas FOREIGN KEY (id_entrada)
        REFERENCES entradas (id_entrada)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_comisiones_cobradas_tarjetas FOREIGN KEY (id_tarjeta)
        REFERENCES tarjetas (id_tarjeta)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_comisiones_cobradas_montos CHECK (monto_transaccion >= 0 AND monto_comision >= 0)
) ENGINE = InnoDB
  COMMENT = 'Registro automático de la comisión cobrada por cada venta';

-- -----------------------------------------------------------------------------
-- Valoraciones anónimas de las salas
-- -----------------------------------------------------------------------------
CREATE TABLE valoraciones (
    id_valoracion INT UNSIGNED     NOT NULL AUTO_INCREMENT
        COMMENT 'Identificador de la valoración',
    id_sala       INT UNSIGNED     NOT NULL
        COMMENT 'Sala valorada (FK a salas)',
    estrellas     TINYINT UNSIGNED NOT NULL
        COMMENT 'Calificación de 1 a 5 estrellas',
    observacion   VARCHAR(500)     NULL
        COMMENT 'Comentario opcional del visitante',
    fecha         DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP
        COMMENT 'Fecha y hora en que se registró la valoración',
    CONSTRAINT pk_valoraciones PRIMARY KEY (id_valoracion),
    INDEX ix_valoraciones_id_sala (id_sala),
    CONSTRAINT fk_valoraciones_salas FOREIGN KEY (id_sala)
        REFERENCES salas (id_sala)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_valoraciones_estrellas CHECK (estrellas BETWEEN 1 AND 5)
) ENGINE = InnoDB
  COMMENT = 'Valoraciones anónimas que los visitantes hacen de cada sala';

-- =============================================================================
-- 2. DISPARADOR: registro automático de comisiones
--    Cada vez que se inserta una entrada, se guarda la comisión que se le debe
--    pagar a la marca de la tarjeta según el porcentaje vigente.
-- =============================================================================
CREATE TRIGGER tg_entradas_ai
AFTER INSERT ON entradas
FOR EACH ROW
INSERT INTO comisiones_cobradas
    (id_entrada, id_tarjeta, porcentaje_aplicado, monto_transaccion, monto_comision, fecha_registro)
SELECT NEW.id_entrada,
       t.id_tarjeta,
       t.porcentaje_comision,
       NEW.total,
       ROUND(NEW.total * t.porcentaje_comision / 100, 2),
       NEW.fecha_compra
FROM tarjetas t
WHERE t.id_tarjeta = NEW.id_tarjeta;

-- =============================================================================
-- 3. VISTAS
-- =============================================================================

-- Promedio y cantidad de valoraciones de cada sala (reporte de valoración)
CREATE VIEW vw_valoracion_salas AS
SELECT s.id_sala,
       s.nombre                              AS sala,
       m.id_museo,
       m.nombre                              AS museo,
       COUNT(v.id_valoracion)                AS cantidad_valoraciones,
       COALESCE(ROUND(AVG(v.estrellas), 2), 0) AS promedio
FROM salas s
JOIN museos m ON m.id_museo = s.id_museo
LEFT JOIN valoraciones v ON v.id_sala = s.id_sala
GROUP BY s.id_sala, s.nombre, m.id_museo, m.nombre;

-- Detalle de cada comisión cobrada con su tarjeta y su entrada
CREATE VIEW vw_comisiones_detalle AS
SELECT c.id_comision,
       c.fecha_registro,
       t.id_tarjeta,
       t.nombre AS tarjeta,
       c.porcentaje_aplicado,
       c.monto_transaccion,
       c.monto_comision,
       e.codigo AS codigo_entrada,
       e.nombre_visitante
FROM comisiones_cobradas c
JOIN tarjetas t ON t.id_tarjeta = c.id_tarjeta
JOIN entradas e ON e.id_entrada = c.id_entrada;

-- Salas disponibles para la venta con su museo y sus tarifas
CREATE VIEW vw_tarifas_salas AS
SELECT s.id_sala,
       s.nombre AS sala,
       m.id_museo,
       m.nombre AS museo,
       p.precio_semana,
       p.precio_domingo
FROM salas s
JOIN museos m  ON m.id_museo = s.id_museo
JOIN precios p ON p.id_sala = s.id_sala;

